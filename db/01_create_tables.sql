CREATE TABLE IF NOT EXISTS public.products
(
    id          INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(150)  NOT NULL,
    description VARCHAR(500)  NULL,
    price       NUMERIC(18,2) NOT NULL,
    stock       INTEGER       NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NULL,

    CONSTRAINT pk_products        PRIMARY KEY (id),
    CONSTRAINT ck_products_price  CHECK (price >= 0),
    CONSTRAINT ck_products_stock  CHECK (stock >= 0),
    CONSTRAINT ck_products_name   CHECK (length(btrim(name)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_products_name_lower ON public.products (lower(name));

COMMENT ON TABLE  public.products             IS 'Catalogo de productos (agregado Product).';
COMMENT ON COLUMN public.products.price       IS 'Precio unitario en USD.';
COMMENT ON COLUMN public.products.stock       IS 'Unidades disponibles en inventario.';
COMMENT ON COLUMN public.products.updated_at  IS 'Ultima modificacion; NULL si nunca se modifico.';
